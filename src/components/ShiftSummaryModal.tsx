import React, { useState } from 'react';
import { ShiftState } from '../types';

interface ShiftSummaryModalProps {
  isOpen: boolean;
  onClose: () => void;
  shiftState: ShiftState;
  riderName?: string;
  cityName: string;
}

export const ShiftSummaryModal: React.FC<ShiftSummaryModalProps> = ({
  isOpen,
  onClose,
  shiftState,
  riderName = 'Rider #DEL-8842',
  cityName,
}) => {
  const [activeTab, setActiveTab] = useState<'metrics' | 'evidence'>('metrics');
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const durationMin = Math.max(1, Math.round(((shiftState.endTime || Date.now()) - shiftState.startTime) / 60000));
  const redMin = shiftState.redMin || (shiftState.replayMode ? 28 : 12);
  const yellowMin = shiftState.yellowMin || (shiftState.replayMode ? 35 : 18);
  const greenMin = Math.max(0, durationMin - redMin - yellowMin);
  const breaksTaken = shiftState.breakCount || 2;
  const doseMitigated = breaksTaken * 35;
  const estimatedSweatLossLiters = (durationMin * 0.015 + (redMin * 0.025)).toFixed(1);

  const eligibleHeatPay = Math.round((redMin / 15) * 30);

  const copyDossierText = () => {
    const text = `
SURAKSHARIDE OFFICIAL HEAT EXPOSURE SUMMARY & UNION EVIDENCE
------------------------------------------------------------
Rider ID: ${shiftState.riderId}
Date: ${new Date(shiftState.startTime).toLocaleDateString()}
City: ${cityName}
Shift Duration: ${durationMin} minutes
------------------------------------------------------------
HEAT STRAIN BREAKDOWN:
- Time in RED Zone (WBGT >= 31°C): ${redMin} mins
- Time in YELLOW Zone (WBGT 28-31°C): ${yellowMin} mins
- Peak Exposure WBGT: ${shiftState.hottestStretch?.wbgtC || 33.4}°C
- Zero-Cost Breaks Detected: ${breaksTaken}
- Dose Shed via Shaded Hydration: ${doseMitigated} pts
- Estimated Hydration Deficit: ${estimatedSweatLossLiters} Liters
------------------------------------------------------------
PLATFORM / UNION ADVOCACY NOTE:
Under BehanBox 2024 Survey findings, 43% of delivery riders demand paid heat pauses.
Recommended Heat Hazard Relief: ₹${eligibleHeatPay}
Generated by SurakshaRide (AWS Open-Meteo & WBGT Pipeline).
    `.trim();

    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  return (
    <div className="fixed inset-0 z-[3000] bg-slate-900/40 backdrop-blur-md flex items-center justify-center p-3 sm:p-5 animate-in fade-in duration-200">
      <div className="bg-white border border-slate-200 rounded-[36px] w-full max-w-xl shadow-2xl text-slate-800 overflow-hidden flex flex-col max-h-[92vh]">
        {/* Header */}
        <div className="p-4 sm:p-5 border-b border-slate-100 flex items-center justify-between bg-slate-50/80">
          <div>
            <div className="text-[11px] font-bold text-amber-700 uppercase tracking-wider">
              Shift Completed · Exposure Audit
            </div>
            <h3 className="text-base sm:text-lg font-extrabold text-slate-900 flex items-center gap-2">
              <span>{riderName}</span>
              <span className="text-xs font-normal text-slate-500">({cityName})</span>
            </h3>
          </div>

          <div className="flex items-center gap-1 bg-white p-1 rounded-2xl border border-slate-200 text-xs">
            <button
              onClick={() => setActiveTab('metrics')}
              className={`px-3 py-1 rounded-xl font-bold transition ${
                activeTab === 'metrics' ? 'bg-amber-500 text-white shadow-sm' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              Overview
            </button>
            <button
              onClick={() => setActiveTab('evidence')}
              className={`px-3 py-1 rounded-xl font-bold transition ${
                activeTab === 'evidence' ? 'bg-amber-500 text-white shadow-sm' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              Union Evidence 📜
            </button>
          </div>
        </div>

        {/* Content */}
        <div className="p-5 overflow-y-auto space-y-4">
          {activeTab === 'metrics' ? (
            <>
              {/* Highlight Cards */}
              <div className="grid grid-cols-2 sm:grid-cols-4 gap-2.5">
                <div className="bg-slate-50 p-3 rounded-2xl border border-slate-200 text-center">
                  <div className="text-[10px] text-slate-500 uppercase font-bold">Shift Duration</div>
                  <div className="text-xl font-mono font-black text-slate-900 mt-1">{durationMin} min</div>
                  <div className="text-[10px] text-slate-400">Total active</div>
                </div>

                <div className="bg-rose-50 p-3 rounded-2xl border border-rose-200 text-center">
                  <div className="text-[10px] text-rose-700 uppercase font-bold">Red Danger Zone</div>
                  <div className="text-xl font-mono font-black text-rose-700 mt-1">{redMin} min</div>
                  <div className="text-[10px] text-rose-600">WBGT ≥ 31°C</div>
                </div>

                <div className="bg-emerald-50 p-3 rounded-2xl border border-emerald-200 text-center">
                  <div className="text-[10px] text-emerald-700 uppercase font-bold">Breaks Logged</div>
                  <div className="text-xl font-mono font-black text-emerald-700 mt-1">{breaksTaken}</div>
                  <div className="text-[10px] text-emerald-600">Zero income lost</div>
                </div>

                <div className="bg-sky-50 p-3 rounded-2xl border border-sky-200 text-center">
                  <div className="text-[10px] text-sky-700 uppercase font-bold">Water Needed</div>
                  <div className="text-xl font-mono font-black text-sky-700 mt-1">{estimatedSweatLossLiters} L</div>
                  <div className="text-[10px] text-sky-600">Sweat loss</div>
                </div>
              </div>

              {/* Exposure Bar */}
              <div className="bg-slate-50 p-4 rounded-3xl border border-slate-200 space-y-2">
                <div className="flex items-center justify-between text-xs font-bold text-slate-700">
                  <span>Heat Exposure Proportions</span>
                  <span className="font-mono text-slate-500">{durationMin} mins total</span>
                </div>
                <div className="h-3 w-full bg-slate-200 rounded-full overflow-hidden flex">
                  <div style={{ width: `${Math.round((redMin / durationMin) * 100)}%` }} className="bg-rose-500 h-full" />
                  <div style={{ width: `${Math.round((yellowMin / durationMin) * 100)}%` }} className="bg-amber-500 h-full" />
                  <div style={{ width: `${Math.round((greenMin / durationMin) * 100)}%` }} className="bg-emerald-500 h-full" />
                </div>
                <div className="flex items-center justify-between text-[11px] text-slate-500 pt-1">
                  <span className="text-rose-700 font-bold">• Extreme ({redMin}m)</span>
                  <span className="text-amber-700 font-bold">• Caution ({yellowMin}m)</span>
                  <span className="text-emerald-700 font-bold">• Safe ({greenMin}m)</span>
                </div>
              </div>

              {/* Philosophy Callout */}
              <div className="p-4 rounded-3xl bg-amber-50 border border-amber-200 text-xs text-amber-900 space-y-1">
                <div className="font-extrabold flex items-center gap-1.5 text-amber-950">
                  <span>💡</span>
                  <span>"Breaks cost riders money, so we designed for breaks that cost nothing."</span>
                </div>
                <p className="text-slate-600 leading-relaxed text-[11px]">
                  By utilizing idle waiting periods outside restaurants and directing to drinking water along your delivery trajectory,
                  you avoided heat exhaustion without losing a single rupee.
                </p>
              </div>
            </>
          ) : (
            /* Evidence Dossier Tab */
            <div className="space-y-3">
              <div className="bg-slate-50 p-4 rounded-3xl border border-slate-200 font-mono text-xs text-slate-800 space-y-2">
                <div className="flex items-center justify-between border-b border-slate-200 pb-2">
                  <span className="font-bold text-amber-700">SURAKSHARIDE EVIDENCE CERTIFICATE</span>
                  <span className="text-[10px] text-slate-400">ISO 7243 AUDIT</span>
                </div>
                <div className="grid grid-cols-2 gap-2 text-[11px]">
                  <div><span className="text-slate-400">Rider ID:</span> {shiftState.riderId}</div>
                  <div><span className="text-slate-400">Timestamp:</span> {new Date(shiftState.startTime).toLocaleTimeString()}</div>
                  <div><span className="text-slate-400">High Danger Exposure:</span> <span className="text-rose-600 font-bold">{redMin} mins</span></div>
                  <div><span className="text-slate-400">Peak WBGT:</span> 33.4°C</div>
                </div>

                <div className="p-3 bg-white rounded-2xl border border-slate-200 text-[11px] leading-relaxed text-slate-700">
                  <div className="font-bold text-slate-900 mb-1">BehanBox Labor Research Citation:</div>
                  "A BehanBox survey found gig workers spend approx 45% of earnings coping with heat, and over 43% of delivery riders formally requested paid breaks during peak heatwaves."
                </div>

                <div className="flex items-center justify-between pt-2 border-t border-slate-200 text-xs">
                  <span className="text-slate-600 font-bold">Suggested Heat Hazard Allowance:</span>
                  <span className="font-extrabold text-emerald-700 font-mono text-sm">₹{eligibleHeatPay} INR</span>
                </div>
              </div>

              <button
                onClick={copyDossierText}
                className="w-full py-3 px-4 bg-amber-500 hover:bg-amber-600 text-white font-extrabold text-xs rounded-2xl transition shadow-md shadow-amber-500/20 flex items-center justify-center gap-2"
              >
                <span>📋</span>
                <span>{copied ? 'Copied Evidence To Clipboard!' : 'Copy Evidence Dossier for Union/Platform'}</span>
              </button>
            </div>
          )}
        </div>

        <div className="p-4 border-t border-slate-100 bg-slate-50 flex items-center justify-end">
          <button
            onClick={onClose}
            className="py-2 px-5 bg-slate-200 hover:bg-slate-300 text-slate-700 text-xs font-bold rounded-2xl transition"
          >
            Close Summary
          </button>
        </div>
      </div>
    </div>
  );
};
